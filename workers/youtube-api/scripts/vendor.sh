#!/usr/bin/env bash
# Rebuild each Worker's python_modules/ from pinned, digest-checked wheels.
# - extract/bundled.whl + extract/bundled.js: the bundled yt-dlp wheel (fallback and
#   rollback target), loaded into the Dynamic Worker sandbox by extract/host.js
# - api/ and updater/python_modules: Workers SDK only (they never import yt-dlp)
# - .vendor/site: yt-dlp unpacked for the CPython unit tests
# Also writes src/bundled.py, which tells the trusted Workers what the bundled copy is.
set -euo pipefail
cd "$(dirname "$0")/.."

ytdlp="https://files.pythonhosted.org/packages/30/1e/f4bf64ca733135e609696c6df77a6c22c6d4909b6e293e4563ae51ea335c/yt_dlp-2026.11.23-py3-none-any.whl e9188e0c559905f7ee05acc1ba0b6fb3f310e7565bf6dea5f62b5300e0775e35"
sdk="https://files.pythonhosted.org/packages/67/1e/cdef3dc0bb249e9e7dee433f6ca8796241328f5134c8d0a97056f064590c/workers_runtime_sdk-1.9.7-py3-none-any.whl 2bda7f2d640aef09cb7c3d2f3c07ad87e649340b313b80b08a06a85b2202bd1e"

fetch() {
  local url="${1% *}" digest="${1#* }"
  local file=".vendor/$(basename "$url")"
  mkdir -p .vendor
  [ -f "$file" ] || curl -fsSL "$url" -o "$file"
  echo "$digest  $file" | sha256sum -c - >&2
  echo "$file"
}

unpack() {  # unpack <wheel> <dir>
  python3 -I -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$1" "$2"
}

ytdlp_file=$(fetch "$ytdlp")
sdk_file=$(fetch "$sdk")
for worker in api updater; do
  rm -rf "$worker/python_modules"
  mkdir -p "$worker/python_modules"
  unpack "$sdk_file" "$worker/python_modules"
done
rm -rf extract/python_modules .vendor/site
unpack "$ytdlp_file" .vendor/site
cp "$ytdlp_file" extract/bundled.whl
version=$(basename "$ytdlp_file" | sed -E 's/^yt_dlp-(.+)-py3-none-any\.whl$/\1/')
echo "export const BUNDLED_VERSION = \"$version\";" > extract/bundled.js
# Keep uploads small: drop data files (man pages, completions) and caches.
rm -rf */python_modules/*.data
find . -path ./.vendor -prune -o -name '__pycache__' -type d -prune -exec rm -rf {} +

python3 -I - "$ytdlp_file" "${ytdlp#* }" > src/bundled.py <<'PY'
import os, re, sys, zipfile
path, digest = sys.argv[1], sys.argv[2]
names = zipfile.ZipFile(path).namelist()
version = re.match(r"yt_dlp-(.+)-py3-none-any\.whl", os.path.basename(path)).group(1)
print('"""Generated by scripts/vendor.sh: the yt-dlp copy bundled in doesitarm-youtube-extract."""')
print()
print(f'VERSION = "{version}"')
print(f'WHEEL_SHA256 = "{digest}"')
print(f"WHEEL_SIZE = {os.path.getsize(path)}")
print(f"WHEEL_FILES = {len(names)}")
PY
echo "vendored; bundled yt-dlp: $(grep VERSION src/bundled.py)"
